class Solution {
public:
    vector<int> preorder(Node* root) {
        vector<int> ans;
        if(root == nullptr){
            return ans;
        }
        ans.push_back(root->val);
        for(Node* child : root->children){
            vector<int> s = preorder(child);
            ans.insert(ans.end(),s.begin(),s.end());
        }
        return ans;   
    }
};

